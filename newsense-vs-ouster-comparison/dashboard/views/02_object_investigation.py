"""Follow One Person (UI v2): investigation list with plain filters and pagination, then one investigation with the camera as the main element."""
import pandas as pd, streamlit as st
from utils import data as D, investigate as I, ui, inv_view as V
from utils.config import C, STATUS_COLOR
from utils.timebase import clock

ui.setup('Follow One Person', 'Select an investigation candidate to see how the two sensors detected and tracked a pedestrian or cyclist.', 'Object investigation')
C_, M_ = D.candidates()
if 'inv' in st.query_params and st.query_params['inv'] in set(C_.inv) and st.session_state.get('_qp') != st.query_params['inv']:
    st.session_state['inv'] = st.session_state['_qp'] = st.query_params['inv']
inv = st.session_state.get('inv')
def pick(e): st.session_state['inv'] = e
def id_cards():
    a, b, c = st.columns(3)
    with a: ui.card(f"<span style='color:{C['NS']}'>Newsense ID</span>", 'The tracking number assigned by Newsense.', 'Newsense and Ouster number objects independently: the same number in both means nothing.', C['NS'])
    with b: ui.card(f"<span style='color:{C['OU']}'>Ouster ID</span>", 'The tracking number assigned by Ouster.', 'One person can receive several IDs if a sensor loses and restarts the track.', C['OU'])
    with c: ui.card("<span style='color:#4338CA'>Investigation number</span>", 'A reference generated by this dashboard to organise a <i>possible</i> cross-sensor match.',
                    '<b>It is not a real person\'s identity</b>, and it does not prove that the Newsense and Ouster tracks are the same person.', '#4338CA')
if not inv: id_cards()
else:
    with st.expander('What do the Newsense ID, Ouster ID and investigation number mean?'): id_cards()

# ---------------------------------------------------------------- examples
EX_TITLE = {'Tracked by both sensors (strong candidate match)': ('Both sensors tracked it', 'Strong candidate match: positions agree closely.'),
            'Newsense-only candidate (unmatched in shared area)': ('Only Newsense reported it', 'No reliable match in Ouster, inside the shared area.'),
            'Ouster-only candidate (unmatched in shared area)': ('Only Ouster reported it', 'No reliable match in Newsense, inside the shared area.'),
            'Ambiguous match (group)': ('Ambiguous: several possible matches', 'Identity cannot be determined.'),
            'Tracking interruption / ID issue (fragmented)': ('Tracking interruption', 'One sensor split the track into several IDs.')}
SHORT = dict(zip(EX_TITLE, ['Both sensors', 'Newsense only', 'Ouster only', 'Ambiguous', 'Interruption']))
ex = I.examples()
st.markdown('### Start with an example' if not inv else '##### Examples')
cols = st.columns(len(ex))
for col, (lab, e) in zip(cols, ex.items()):
    t, d = EX_TITLE[lab]
    if inv:
        if e: col.button(SHORT[lab], key=f'exc_{e}', width='stretch', type='primary' if inv == e else 'secondary', help=f'{d} ({V.label(e)})', on_click=pick, args=(e,))
        continue
    with col.container(border=True):
        st.markdown(f"**{t}**  \n<span style='color:#64748B;font-size:.86rem'>{d}</span>", unsafe_allow_html=True)
        if e is None: st.button('No valid example', disabled=True, key=f'exn_{lab}', width='stretch')
        else: st.button(f'Open {V.label(e).replace("Investigation ", "")}', key=f'ex_{e}', width='stretch', on_click=pick, args=(e,))

# ---------------------------------------------------------------- find an investigation
with st.expander('Find an investigation', expanded=inv is None):
    f1, f2 = st.columns([1, 1])
    typ = f1.pills('Object type', ['Pedestrians', 'Cyclists'], selection_mode='multi', default=['Pedestrians', 'Cyclists'], key='f_type')
    det = f2.pills('Detected by', ['Both sensors detected', 'Newsense only', 'Ouster only'], selection_mode='multi', default=['Both sensors detected', 'Newsense only', 'Ouster only'], key='f_det')
    res = st.pills('Match result', ['Strong candidate match', 'Possible match', 'Ambiguous matches', 'No reliable match', 'Cannot determine'], selection_mode='multi',
                   default=['Strong candidate match', 'Possible match', 'Ambiguous matches', 'No reliable match'], key='f_res')
    extra = st.pills('Only show', ['Tracking interruptions', 'Visible in the camera view'], selection_mode='multi', default=[], key='f_extra',
                     help='Tracking interruptions: at least one sensor split the object into several track pieces, or re-used / re-attached a tracking ID.')
    with st.popover('More filters'):
        moving = st.checkbox('Moving objects only (moved more than 2 m)', True, key='f_moving')
        motor = st.checkbox('Include Newsense "Motorcycle" labels (often bicycles, see methodology)', False, key='f_moto')
        dmin = st.number_input('Minimum tracking duration (s)', 0.0, 600.0, 3.0, 1.0, key='f_dmin')
        tmin, tmax = float(C_.t0.min()), float(C_.t1.max())
        tr = st.slider('Time window (seconds after 07:12)', 0, int(tmax - tmin), (0, int(tmax - tmin)), step=30, key='f_time'); st.caption(f'{clock(tmin + tr[0])} – {clock(tmin + tr[1])}')
        nsid = st.text_input('Newsense ID contains', key='f_ns'); ouid = st.text_input('Ouster ID contains', key='f_ou')
    RES = {'Strong candidate match': 'Strong candidate match', 'Possible match': 'Possible match', 'Ambiguous matches': 'Ambiguous', 'No reliable match': 'Unmatched', 'Cannot determine': 'Cannot determine'}
    DET = {'Both sensors detected': 'both', 'Newsense only': 'Newsense only', 'Ouster only': 'Ouster only'}
    grp = (['PED'] if 'Pedestrians' in typ else []) + (['CYC'] if 'Cyclists' in typ else []) + (['MOTO'] if motor else [])
    q = C_[C_.status.isin([RES[r] for r in res]) & C_.sensors.isin([DET[d] for d in det]) & (C_.dur >= dmin) & (C_.t1 >= tmin + tr[0]) & (C_.t0 <= tmin + tr[1])]
    q = q[pd.Series([any(g in (x, y) for g in grp) for x, y in zip(q.ns_class, q.ou_class)], index=q.index, dtype=bool)]
    if moving: q = q[q.moving]
    if 'Tracking interruptions' in extra: q = q[q.fragmented | q.id_issue]
    if 'Visible in the camera view' in extra: q = q[pd.Series([I.in_camera(x, y) for x, y in zip(q.x, q.y)], index=q.index, dtype=bool)]
    if nsid: q = q[q.ns_ids.str.contains(nsid, regex=False)]
    if ouid: q = q[q.ou_ids.str.contains(ouid, regex=False)]
    s1, s2, s3 = st.columns([2, 1, 1])
    sort = s1.segmented_control('Sort by', ['Time', 'Longest tracking', 'Match result'], default='Time', key='f_sort') or 'Time'
    q = q.sort_values({'Time': 't0', 'Longest tracking': 'dur', 'Match result': 'status'}[sort], ascending=sort != 'Longest tracking')
    PER = 12; pages = max(1, -(-len(q) // PER))
    page = s3.number_input(f'Page (of {pages:,})', 1, pages, 1, key='f_page')
    s2.markdown(f"<div style='padding-top:1.9rem;color:#475569'>{len(q):,} of {len(C_):,} investigations</div>", unsafe_allow_html=True)
    p = q.iloc[(page - 1) * PER: page * PER]
    yes = lambda v: '✓ Yes' if v else '— No'
    tbl = pd.DataFrame({'Investigation': [V.label(i) for i in p.inv], 'Object type': [V.object_type(a, b) for a, b in zip(p.ns_class, p.ou_class)],
                        'Newsense detected?': [yes(s != 'Ouster only') for s in p.sensors], 'Ouster detected?': [yes(s != 'Newsense only') for s in p.sensors],
                        'Tracking duration': [f'{d:.1f} s' for d in p.dur], 'Match result': [ui.STATUS_PLAIN[s][0] for s in p.status], 'View investigation': ['Open ›'] * len(p)}).reset_index(drop=True)
    colors = {ui.STATUS_PLAIN[k][0]: v for k, v in STATUS_COLOR.items()}
    sty = tbl.style.map(lambda v: f'color:{colors.get(v, "#0F172A")};font-weight:600', subset=['Match result']).map(lambda v: 'color:#4338CA;font-weight:600', subset=['View investigation']) \
        .map(lambda v: 'color:#94A3B8' if v.startswith('—') else 'color:#0F172A', subset=['Newsense detected?', 'Ouster detected?'])
    st.caption(f'Showing {(page - 1) * PER + 1 if len(q) else 0}–{min(page * PER, len(q))} · click a row to open it. Times are 29 Oct 2026, 07:12–08:35, when both sensors recorded.')
    sel = st.dataframe(sty, hide_index=True, width='stretch', height=35 * (len(tbl) + 1) + 3, on_select='rerun', selection_mode='single-row', key=f'tbl_{page}_{len(q)}')
    if sel and sel.selection.rows: st.session_state['inv'] = inv = p.iloc[sel.selection.rows[0]].inv
    exp = q.assign(first_cet=[clock(t, True) for t in q.t0], last_cet=[clock(t, True) for t in q.t1])[['inv', 'status', 'sensors', 'ns_ids', 'ou_ids', 'ns_class', 'ou_class', 'first_cet', 'last_cet', 'dur', 'n_obs', 'ns_segments', 'ou_segments', 'best_median_d', 'fragmented', 'id_issue', 'class_change']]
    st.download_button('Download the filtered list (CSV, technical columns)', exp.to_csv(index=False).encode(), 'k305_investigations_filtered.csv', 'text/csv')

if not inv:
    ui.info('Choose an example above or open <b>Find an investigation</b> and click a row.'); st.stop()
st.query_params['inv'] = inv
X = V.load(inv)
V.header(X)
V.play(X)
V.tracking_cards(X)
V.match_explanation(X)
V.comparison_table(X)
ui.glossary(['Tracking ID', 'Investigation number', 'Track fragmentation', 'Tracking interruption', 'Estimated position', 'Classification change', 'Recorded sensor sample', 'Movement distance'])
V.technical(X)
